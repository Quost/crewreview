#!/usr/bin/env bun
// Write the Homebrew formula and the Scoop manifest for a release, from its SHA256SUMS.
//   bun scripts/package-manifests.ts <version> <path/to/SHA256SUMS>
// Homebrew: brew tap Quost/crewreview https://github.com/Quost/crewreview && brew install crewreview
// Scoop:    scoop bucket add crewreview https://github.com/Quost/crewreview && scoop install crewreview
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const [version, sumsPath] = process.argv.slice(2);
if (!version || !sumsPath || !/^\d+\.\d+\.\d+$/.test(version)) {
  console.error("usage: bun scripts/package-manifests.ts <x.y.z> <SHA256SUMS>");
  process.exit(2);
}
const sums = new Map(
  (await readFile(sumsPath, "utf8"))
    .split("\n")
    .map((l) => l.trim().split(/\s+/))
    .filter((p) => p.length === 2)
    .map(([hash, name]) => [name!.replace(/^\*/, ""), hash!]),
);
const need = (name: string) => {
  const h = sums.get(name);
  if (!h) throw new Error(`${name} missing from SHA256SUMS`);
  return h;
};
const ROOT = join(import.meta.dir, "..");
const url = (name: string) => `https://github.com/Quost/crewreview/releases/download/v${version}/${name}`;
const desc = "Crew of AI agents that reviews pull requests and answers the reviews on yours";

const formula = `# Generated by scripts/package-manifests.ts for each release. Don't edit by hand.
class Crewreview < Formula
  desc "${desc}"
  homepage "https://crewreview.web.app"
  version "${version}"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "${url("crewreview-darwin-arm64")}"
      sha256 "${need("crewreview-darwin-arm64")}"
    end
    on_intel do
      url "${url("crewreview-darwin-x64")}"
      sha256 "${need("crewreview-darwin-x64")}"
    end
  end

  on_linux do
    on_arm do
      url "${url("crewreview-linux-arm64")}"
      sha256 "${need("crewreview-linux-arm64")}"
    end
    on_intel do
      url "${url("crewreview-linux-x64")}"
      sha256 "${need("crewreview-linux-x64")}"
    end
  end

  def install
    bin.install Dir["crewreview-*"].first => "crewreview"
  end

  service do
    run [opt_bin/"crewreview", "run"]
    keep_alive successful_exit: false
    log_path var/"log/crewreview.log"
    error_log_path var/"log/crewreview.log"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/crewreview --version").strip
  end
end
`;

const scoop = {
  version,
  description: desc,
  homepage: "https://crewreview.web.app",
  license: "AGPL-3.0-only",
  architecture: { "64bit": { url: `${url("crewreview-windows-x64.exe")}#/crewreview.exe`, hash: need("crewreview-windows-x64.exe") } },
  bin: "crewreview.exe",
  checkver: { github: "https://github.com/Quost/crewreview" },
  autoupdate: {
    architecture: { "64bit": { url: "https://github.com/Quost/crewreview/releases/download/v$version/crewreview-windows-x64.exe#/crewreview.exe" } },
    hash: { url: "$baseurl/SHA256SUMS", regex: "$sha256\\s+crewreview-windows-x64.exe" },
  },
};

await mkdir(join(ROOT, "Formula"), { recursive: true });
await mkdir(join(ROOT, "bucket"), { recursive: true });
await writeFile(join(ROOT, "Formula", "crewreview.rb"), formula);
await writeFile(join(ROOT, "bucket", "crewreview.json"), `${JSON.stringify(scoop, null, 2)}\n`);
console.log(`Formula/crewreview.rb and bucket/crewreview.json for ${version}`);
